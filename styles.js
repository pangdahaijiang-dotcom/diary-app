// 拼装完整生成指令。
// · genStyle.pure === true → 纯模仿：只拼 GEN_MINE_RULES + GEN_FORMAT。
// · 其他风格 → 底座三件套 + 该风格的 genTwist。
//   opts.withExamples === false → 用 GEN_EXAMPLES_OMITTED 替代内置范例
//   （场景：用户提供了「我的文风」样本，语气只以本人样本为准）
function buildGen(genStyle, opts) {
  opts = opts || {};
  if (genStyle.pure) {
    return [GEN_MINE_RULES, GEN_FORMAT].join("\n\n") + "\n";
  }
  const withExamples = opts.withExamples !== false;
  const parts = [
    GEN_BASE_RULES,
    withExamples ? GEN_EXAMPLES : GEN_EXAMPLES_OMITTED,
    GEN_FORMAT,
    "【本次生成风格补充】\n" + genStyle.genTwist,
  ];
  return parts.join("\n\n") + "\n";
}
